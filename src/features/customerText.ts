export function useCustomerText() {
  const { language } = useUI();
  return {
    language,
    t: (text: string) => (language === "en" ? (EN[text] ?? text) : text),
    syp: (amount: number) =>
      language === "en"
        ? `${new Intl.NumberFormat("en").format(amount)} SYP`
        : `${new Intl.NumberFormat("ar-SY").format(amount)} ل.س`,
  };
}
